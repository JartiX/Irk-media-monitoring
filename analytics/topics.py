"""
Тематическая категоризация (виды туризма).

Категория определяется по ключевым словам; возвращается доминирующая (макс. число совпадений) либо None.
"""
from __future__ import annotations

import re

import pandas as pd

# категория -> regex ключевых слов/основ
_CATEGORIES = {
    "активный": r"поход(?!у)|треккинг|хайкинг|\bсплав\b|рафтинг|рафт\b|восхожд|"
                r"кат(ать|аем|ал)|лыж|сноуборд|велосипед|велотур|вело\b|джип|снегоход|квадроцикл|"
                r"мотоцикл|покорить|трек\b|тропа|тропе|перевал|альпин|скалолаз|зиплайн|пеший|пешком|сафари",
    "пляжный/отдых": r"пляж|купа|искупа|загора|загар|солнечн|\bотдых|турбаз|база отдыха|кемпинг|"
                     r"глэмпинг|палатк|шашлык|пикник|костёр|костра|загорал|отдохну",
    "экскурсионный": r"экскурс|музе|выставк|достоприм|посет|осмотр|побыва|памятник|обзорн|\bгид\b|"
                     r"экспозиц|экскурсовод|архитектур|усадьб|истори|краеведч|обзорн",
    "рыбалка/охота": r"рыбалк|рыбач|удочк|спиннинг|\bулов|кл[ею][её]т|\bохот|айсфишинг|фотоохот",
    "гастрономический": r"кафе|ресторан|\bеда\b|кухн|попробова|дегустац|бууз|омул|блюд|"
                        r"вкусн|кулинар|гастро|местн(ая|ую)\s+еда|сагудай|строганин",
    "оздоровительный": r"санатор|курорт|\bисточник|минеральн|лечен|оздоров|ретрит|\bспа\b|термальн|"
                       r"аршан|массаж|грязелеч|велнес|профилактор",
    "событийный/культурный": r"фестивал|праздник|ярмарк|дацан|шаман|сагаалган|традиц|концерт|обряд|"
                             r"этно|карнавал|\bшоу\b|соревнован|форум|выступлен|мастер-класс",
    "водный/круиз": r"круиз|яхт|катер|теплоход|паром|переправ|\bсап\b|с[её]рф|каяк|каноэ|катамаран|"
                    r"\bлодк|парусник|прогулк(а|у|и)\s+на",
}
_COMPILED = {k: re.compile(v, re.IGNORECASE) for k, v in _CATEGORIES.items()}

CATEGORIES = list(_CATEGORIES.keys())


def classify(text: str) -> str | None:
    """Доминирующая тематическая категория текста (или None)."""
    if not text:
        return None
    best, best_n = None, 0
    for cat, rx in _COMPILED.items():
        n = len(rx.findall(text))
        if n > best_n:
            best, best_n = cat, n
    return best


def classify_series(texts: pd.Series) -> pd.Series:
    """Категория для каждого текста (пустая строка вместо None)."""
    return texts.map(lambda s: classify(s) or "")
